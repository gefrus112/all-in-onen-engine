// SNAKE
// ---------------------------------------------------------------------------
function snakeCode(p: GameParams): string {
  return `"""
${p.title} — Snake · generated by ${p.model}
Controls: arrow keys / WASD · Space restarts after a crash
"""
from lapia_shim import Game, Scene, Vector2, Color, Math

GRID_W, GRID_H = 24, 18
CELL = 32

class SnakeScene(Scene):
    def on_load(self):
        self.bg_color = Color(12, 14, 24)
        self.best = 0
        self.reset()

    def reset(self):
        self.snake = [Vector2(6, 9), Vector2(5, 9), Vector2(4, 9)]
        self.dir = Vector2(1, 0)
        self.next_dir = Vector2(1, 0)
        self.step = 0.0
        self.interval = 0.13 / ${p.speed}
        self.score = 0
        self.dead = False
        self.flash = 0.0
        self.spawn_food()

    def spawn_food(self):
        while True:
            f = Vector2(Math.random_int(1, GRID_W - 2), Math.random_int(1, GRID_H - 2))
            if all(s.x != f.x or s.y != f.y for s in self.snake):
                self.food = f
                return

    def on_update(self, dt):
        inp = self.input
        if self.dead:
            self.flash = max(0.0, self.flash - dt)
            if inp.key_pressed('space') or inp.key_pressed('enter'):
                self.reset()
            return
        if inp.key_pressed('up') or inp.key_pressed('w'):
            if self.dir.y == 0: self.next_dir = Vector2(0, -1)
        elif inp.key_pressed('down') or inp.key_pressed('s'):
            if self.dir.y == 0: self.next_dir = Vector2(0, 1)
        elif inp.key_pressed('left') or inp.key_pressed('a'):
            if self.dir.x == 0: self.next_dir = Vector2(-1, 0)
        elif inp.key_pressed('right') or inp.key_pressed('d'):
            if self.dir.x == 0: self.next_dir = Vector2(1, 0)

        self.step += dt
        if self.step < self.interval:
            return
        self.step = 0.0
        self.dir = self.next_dir
        head = Vector2(self.snake[0].x + self.dir.x, self.snake[0].y + self.dir.y)
        hit_wall = head.x < 0 or head.y < 0 or head.x >= GRID_W or head.y >= GRID_H
        hit_self = any(s.x == head.x and s.y == head.y for s in self.snake)
        if hit_wall or hit_self:
            self.dead = True
            self.flash = 1.0
            self.best = max(self.best, self.score)
            print(f"Game over! Score: {self.score}")
            return
        self.snake.insert(0, head)
        if head.x == self.food.x and head.y == self.food.y:
            self.score += 10
            self.interval = max(0.055, self.interval * 0.982)
            self.spawn_food()
        else:
            self.snake.pop()

    def on_render(self, r):
        # subtle grid
        for gx in range(GRID_W + 1):
            r.draw_line(Vector2(gx * CELL, 0), Vector2(gx * CELL, GRID_H * CELL), Color(255, 255, 255, 7), 1)
        for gy in range(GRID_H + 1):
            r.draw_line(Vector2(0, gy * CELL), Vector2(GRID_W * CELL, gy * CELL), Color(255, 255, 255, 7), 1)
        # food
        r.fill_circle(Vector2(self.food.x * CELL + 16, self.food.y * CELL + 16), 10, ${C(p.enemyRGB)})
        # snake
        n = len(self.snake)
        for i, s in enumerate(self.snake):
            t = 1.0 - i / max(1, n)
            col = Color(${p.playerRGB[0]}, ${p.playerRGB[1]}, ${p.playerRGB[2]}, int(140 + 115 * t))
            r.fill_rect(Vector2(s.x * CELL + 2, s.y * CELL + 2), Vector2(CELL - 4, CELL - 4), col)
        # HUD
        r.draw_text(Vector2(14, 10), f"Score: {self.score}", color=Color(235, 240, 250), size=22)
        r.draw_text(Vector2(14, 36), f"Best: {self.best}", color=Color(150, 158, 180), size=15)
        if self.dead:
            r.fill_rect(Vector2(0, 0), Vector2(GRID_W * CELL, GRID_H * CELL), Color(6, 8, 14, 170))
            r.draw_text(Vector2(GRID_W * 16, GRID_H * 16 - 30), "GAME OVER", color=${C(p.enemyRGB)}, size=44)
            r.draw_text(Vector2(GRID_W * 16, GRID_H * 16 + 12), "Space to try again", color=Color(200, 205, 220), size=18)

game = Game(title="${p.title}", size=(GRID_W * CELL, GRID_H * CELL), fps=60)
game.run(SnakeScene())
`;
}

