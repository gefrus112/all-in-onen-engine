function flappyCode(p: GameParams): string {
  return `"""
${p.title} — Flappy Flier · generated by ${p.model}
Controls: Space / click to flap
"""
from lapia_shim import Game, Scene, Vector2, Color, Math

W, H = 720, 600
GAP = 190
PIPE_W = 70

class FlappyScene(Scene):
    def on_load(self):
        self.bg_color = Color(16, 20, 34)
        self.bird = Vector2(200, H / 2)
        self.vel = 0.0
        self.pipes = []
        self.scroll = 0.0
        self.spacing = 250 / ${p.speed}
        self.started = False
        self.dead = False
        self.score = 0
        self.best = 0
        for i in range(3):
            self.add_pipe(W + 150 + i * self.spacing)

    def add_pipe(self, x):
        gap_y = Math.random_range(140, H - 140)
        self.pipes.append({'x': x, 'gap_y': gap_y, 'passed': False})

    def flap(self):
        if self.dead:
            self.on_load()
            return
        self.started = True
        self.vel = -330

    def on_update(self, dt):
        if self.input.key_pressed('space') or self.input.mouse_pressed(1):
            self.flap()
        if self.dead or not self.started:
            return
        self.vel += 900 * dt
        self.bird.y += self.vel * dt

        for pipe in self.pipes:
            pipe['x'] -= 160 * ${p.speed} * dt
        if self.pipes and self.pipes[0]['x'] < -PIPE_W - 10:
            self.pipes.pop(0)
        if self.pipes and self.pipes[-1]['x'] < W:
            self.add_pipe(self.pipes[-1]['x'] + self.spacing)

        for pipe in self.pipes:
            if not pipe['passed'] and pipe['x'] + PIPE_W < self.bird.x:
                pipe['passed'] = True
                self.score += 1
                if self.score > self.best: self.best = self.score

        # collisions
        if self.bird.y > H - 24 or self.bird.y < -20:
            self.dead = True
            print(f"Crashed! Score: {self.score}")
        for pipe in self.pipes:
            if abs(pipe['x'] + PIPE_W / 2 - self.bird.x) < PIPE_W / 2 + 14:
                if abs(self.bird.y - pipe['gap_y']) > GAP / 2 - 8:
                    self.dead = True

    def on_render(self, r):
        ${p.juice >= 1 ? `# parallax hills
        r.fill_rect(Vector2(0, H - 46), Vector2(W, 46), Color(24, 30, 48))
        for i in range(0, W + 60, 60):
            x = (i - (self.scroll if hasattr(self, 'scroll') else 0)) % (W + 60)
            r.fill_circle(Vector2(x, H - 40), 26, Color(26, 33, 54))
` : ""}
        for pipe in self.pipes:
            top_h = pipe['gap_y'] - GAP / 2
            bot_y = pipe['gap_y'] + GAP / 2
            r.fill_rect(Vector2(pipe['x'], 0), Vector2(PIPE_W, top_h), ${C(p.accentRGB)})
            r.fill_rect(Vector2(pipe['x'] - 5, top_h - 20), Vector2(PIPE_W + 10, 20), ${C(p.accentRGB)})
            r.fill_rect(Vector2(pipe['x'], bot_y), Vector2(PIPE_W, H - bot_y), ${C(p.accentRGB)})
            r.fill_rect(Vector2(pipe['x'] - 5, bot_y), Vector2(PIPE_W + 10, 20), ${C(p.accentRGB)})
        # bird
        r.fill_circle(self.bird, 14, ${C(p.playerRGB)})
        r.fill_circle(Vector2(self.bird.x + 6, self.bird.y - 4), 4, Color(20, 22, 30))
        r.draw_text(Vector2(W / 2, 40), str(self.score), color=Color(240, 244, 255), size=52)
        r.draw_text(Vector2(W / 2, 92), f"Best: {self.best}", color=Color(150, 158, 180), size=16)
        if not self.started and not self.dead:
            r.draw_text(Vector2(W / 2, H / 2 + 90), "Space or click to start", color=Color(200, 205, 220), size=20)
        if self.dead:
            r.fill_rect(Vector2(0, 0), Vector2(W, H), Color(6, 8, 14, 150))
            r.draw_text(Vector2(W / 2, H / 2 - 16), "SPLAT!", color=${C(p.enemyRGB)}, size=52)
            r.draw_text(Vector2(W / 2, H / 2 + 34), "Space to fly again", color=Color(200, 205, 220), size=18)

game = Game(title="${p.title}", size=(W, H), fps=60)
game.run(FlappyScene())
`;
}

