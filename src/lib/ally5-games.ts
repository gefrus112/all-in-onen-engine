function pongCode(p: GameParams): string {
  return `"""
${p.title} — Pong · generated by ${p.model}
Controls: mouse or up/down keys · first to 5 wins
"""
from lapia_shim import Game, Scene, Vector2, Color, Math

W, H = 800, 560
PADDLE_H = 96
WIN_SCORE = 5

class PongScene(Scene):
    def on_load(self):
        self.bg_color = Color(10, 12, 20)
        self.player_y = H / 2
        self.ai_y = H / 2
        self.score_p = 0
        self.score_a = 0
        self.serve(1)

    def serve(self, direction):
        self.ball = Vector2(W / 2, H / 2)
        ang = Math.random_range(-0.6, 0.6)
        spd = 340 * ${p.speed}
        self.vel = Vector2(Math.cos(ang) * direction * spd, Math.sin(ang) * spd)
        self.hits = 0

    def on_update(self, dt):
        inp = self.input
        # player paddle: mouse takes priority, keys as backup
        if inp.mouse_position.y > 1:
            self.player_y = inp.mouse_position.y
        if inp.key_down('up') or inp.key_down('w'): self.player_y -= 420 * dt
        if inp.key_down('down') or inp.key_down('s'): self.player_y += 420 * dt
        self.player_y = Math.clamp(self.player_y, PADDLE_H / 2, H - PADDLE_H / 2)

        # simple AI: track ball with limited speed
        target = self.ball.y
        self.ai_y += Math.clamp(target - self.ai_y, -1, 1) * (250 * ${p.speed}) * dt * (1.0 if self.vel.x > 0 else 0.45)
        self.ai_y = Math.clamp(self.ai_y, PADDLE_H / 2, H - PADDLE_H / 2)

        self.ball += self.vel * dt

        # wall bounces
        if self.ball.y < 10 or self.ball.y > H - 10:
            self.vel.y *= -1
            self.ball.y = Math.clamp(self.ball.y, 10, H - 10)

        # paddle collisions
        if self.vel.x < 0 and self.ball.x < 34 and self.ball.x > 20 and abs(self.ball.y - self.player_y) < PADDLE_H / 2 + 8:
            self.vel.x = abs(self.vel.x) * 1.06
            self.vel.y += (self.ball.y - self.player_y) * 6
            self.hits += 1
        if self.vel.x > 0 and self.ball.x > W - 34 and self.ball.x < W - 20 and abs(self.ball.y - self.ai_y) < PADDLE_H / 2 + 8:
            self.vel.x = -abs(self.vel.x) * 1.06
            self.vel.y += (self.ball.y - self.ai_y) * 6
            self.hits += 1

        # scoring
        if self.ball.x < -10:
            self.score_a += 1; self.serve(1)
        if self.ball.x > W + 10:
            self.score_p += 1; self.serve(-1)

    def on_render(self, r):
        # center dashed line
        for y in range(0, H, 36):
            r.fill_rect(Vector2(W / 2 - 3, y + 6), Vector2(6, 20), Color(255, 255, 255, 36))
        r.fill_rect(Vector2(22, self.player_y - PADDLE_H / 2), Vector2(12, PADDLE_H), ${C(p.playerRGB)})
        r.fill_rect(Vector2(W - 34, self.ai_y - PADDLE_H / 2), Vector2(12, PADDLE_H), ${C(p.enemyRGB)})
        r.fill_circle(self.ball, 8, Color(250, 250, 255))
        r.draw_text(Vector2(W / 2 - 70, 18), str(self.score_p), color=${C(p.playerRGB)}, size=42)
        r.draw_text(Vector2(W / 2 + 44, 18), str(self.score_a), color=${C(p.enemyRGB)}, size=42)
        if self.score_p >= WIN_SCORE or self.score_a >= WIN_SCORE:
            msg = "YOU WIN!" if self.score_p >= WIN_SCORE else "CPU WINS"
            r.fill_rect(Vector2(0, 0), Vector2(W, H), Color(6, 8, 14, 160))
            r.draw_text(Vector2(W / 2, H / 2), msg, color=Color(240, 244, 255), size=48)
            r.draw_text(Vector2(W / 2, H / 2 + 44), "Space for a rematch", color=Color(200, 205, 220), size=18)
            if self.input.key_pressed('space'):
                self.score_p = 0; self.score_a = 0; self.serve(1)

game = Game(title="${p.title}", size=(W, H), fps=60)
game.run(PongScene())
`;
}

