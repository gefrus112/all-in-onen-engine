// BREAKOUT
// ---------------------------------------------------------------------------
function breakoutCode(p: GameParams): string {
  return `"""
${p.title} — Breakout · generated by ${p.model}
Controls: mouse or arrow keys · clears bricks to win
"""
from lapia_shim import Game, Scene, Vector2, Color, Math

W, H = 800, 600
COLS, ROWS = 10, 6
BW, BH = 72, 24

class BreakoutScene(Scene):
    def on_load(self):
        self.bg_color = Color(12, 13, 22)
        self.paddle = W / 2
        self.bricks = []
        for row in range(ROWS):
            for col in range(COLS):
                self.bricks.append({'x': 13 + col * (BW + 6), 'y': 60 + row * (BH + 8), 'row': row})
        self.reset_ball()
        self.score = 0
        self.lives = 3
        self.won = False
        self.over = False

    def reset_ball(self):
        self.ball = Vector2(W / 2, H - 90)
        ang = Math.random_range(-0.5, 0.5) - 1.57
        self.vel = Vector2(Math.cos(ang), Math.sin(ang)) * (330 * ${p.speed})

    def on_update(self, dt):
        if self.over or self.won:
            if self.input.key_pressed('space'):
                self.on_load()
            return
        inp = self.input
        if inp.mouse_position.x > 1: self.paddle = inp.mouse_position.x
        if inp.key_down('left') or inp.key_down('a'): self.paddle -= 480 * dt
        if inp.key_down('right') or inp.key_down('d'): self.paddle += 480 * dt
        self.paddle = Math.clamp(self.paddle, 60, W - 60)

        self.ball += self.vel * dt
        if self.ball.x < 10 or self.ball.x > W - 10:
            self.vel.x *= -1; self.ball.x = Math.clamp(self.ball.x, 10, W - 10)
        if self.ball.y < 10:
            self.vel.y *= -1; self.ball.y = 10
        if self.ball.y > H + 16:
            self.lives -= 1
            if self.lives <= 0: self.over = True
            else: self.reset_ball()

        # paddle bounce
        if self.vel.y > 0 and self.ball.y > H - 42 and self.ball.y < H - 26 and abs(self.ball.x - self.paddle) < 62:
            self.vel.y = -abs(self.vel.y) * 1.03
            self.vel.x += (self.ball.x - self.paddle) * 5

        # bricks
        for b in self.bricks[:]:
            if abs(self.ball.x - (b['x'] + BW / 2)) < BW / 2 + 7 and abs(self.ball.y - (b['y'] + BH / 2)) < BH / 2 + 7:
                self.bricks.remove(b)
                self.vel.y *= -1
                self.score += (ROWS - b['row']) * 10
                break
        if not self.bricks:
            self.won = True

    def on_render(self, r):
        for b in self.bricks:
            shade = 200 - b['row'] * 22
            r.fill_rect(Vector2(b['x'], b['y']), Vector2(BW, BH), Color(${p.accentRGB[0]}, ${p.accentRGB[1]}, ${p.accentRGB[2]}, shade))
        r.fill_rect(Vector2(self.paddle - 60, H - 34), Vector2(120, 14), ${C(p.playerRGB)})
        r.fill_circle(self.ball, 8, Color(250, 250, 255))
        r.draw_text(Vector2(16, 12), f"Score: {self.score}", color=Color(235, 240, 250), size=22)
        r.draw_text(Vector2(W - 120, 12), "Lives: " + str(self.lives), color=${C(p.enemyRGB)}, size=22)
        if self.won:
            r.fill_rect(Vector2(0, 0), Vector2(W, H), Color(6, 8, 14, 160))
            r.draw_text(Vector2(W / 2, H / 2 - 16), "BOARD CLEARED!", color=${C(p.accentRGB)}, size=44)
            r.draw_text(Vector2(W / 2, H / 2 + 30), "Space to play again", color=Color(200, 205, 220), size=18)
        if self.over:
            r.fill_rect(Vector2(0, 0), Vector2(W, H), Color(6, 8, 14, 170))
            r.draw_text(Vector2(W / 2, H / 2 - 16), "GAME OVER", color=${C(p.enemyRGB)}, size=48)
            r.draw_text(Vector2(W / 2, H / 2 + 30), "Space to retry", color=Color(200, 205, 220), size=18)

game = Game(title="${p.title}", size=(W, H), fps=60)
game.run(BreakoutScene())
`;
}

// ---------------------------------------------------------------------------
// TOP-DOWN COIN COLLECTOR (showcases real sprite assets via load_image)
// ---------------------------------------------------------------------------
function collectCode(p: GameParams): string {
  return `"""
${p.title} — Coin Collector · generated by ${p.model}
Controls: WASD / arrow keys · grab the loot before the timer ends
Real sprite assets are loaded from the toolbox with load_image().
"""
from lapia_shim import Game, Scene, Sprite, Vector2, Color, Math, load_image

W, H = 800, 576
TIME_LIMIT = 45

class CollectScene(Scene):
    def on_load(self):
        self.bg_color = Color(14, 18, 28)
        self.player = Sprite(image=load_image("sprites/player/knight.png"), size=(36, 36))
        self.player.position = Vector2(W / 2, H / 2)
        self.coins = []
        for i in range(${p.coins}):
            s = Sprite(image=load_image("sprites/coins/coin_gold.png"), size=(22, 22))
            s.position = Vector2(Math.random_range(40, W - 40), Math.random_range(40, H - 40))
            self.coins.append({'s': s, 'got': False, 't': Math.random_range(0, 6.28)})
        self.ghost = Sprite(image=load_image("sprites/enemies/slime_green.png"), size=(34, 34))
        self.ghost.position = Vector2(60, 60)
        self.ghost_dir = Vector2(1, 0.4)
        self.score = 0
        self.timer = TIME_LIMIT
        self.over = False
        self.win = False

    def on_update(self, dt):
        if self.over:
            if self.input.key_pressed('space') or self.input.key_pressed('enter'):
                self.on_load()
            return
        inp = self.input
        mv = Vector2(0, 0)
        if inp.key_down('w') or inp.key_down('up'): mv.y -= 1
        if inp.key_down('s') or inp.key_down('down'): mv.y += 1
        if inp.key_down('a') or inp.key_down('left'): mv.x -= 1
        if inp.key_down('d') or inp.key_down('right'): mv.x += 1
        self.player.position += mv.normalized * (250 * ${p.speed}) * dt
        self.player.position.x = Math.clamp(self.player.position.x, 18, W - 18)
        self.player.position.y = Math.clamp(self.player.position.y, 18, H - 18)
        if mv.x != 0:
            self.player.flip_x = mv.x < 0

        for c in self.coins:
            if c['got']: continue
            c['t'] += dt
            c['s'].position = Vector2(c['s'].position.x, c['s'].position.y + Math.sin(c['t'] * 3) * 0.6)
            if c['s'].position.distance_to(self.player.position) < 26:
                c['got'] = True
                c['s'].visible = False
                self.score += 10

        # wandering slime chases slowly
        to_player = self.player.position - self.ghost.position
        self.ghost_dir = (self.ghost_dir + to_player.normalized * 0.6 * dt).normalized
        self.ghost.position += self.ghost_dir * (95 * ${p.speed}) * dt
        if self.ghost.position.distance_to(self.player.position) < 28:
            self.over = True
            print("The slime got you!")

        self.timer -= dt
        if self.timer <= 0:
            self.over = True
            self.win = self.score >= ${p.coins} * 10 / 2

    def on_render(self, r):
        # checker floor
        for gy in range(0, H // 32 + 1):
            for gx in range(0, W // 32 + 1):
                if (gx + gy) % 2 == 0:
                    r.fill_rect(Vector2(gx * 32, gy * 32), Vector2(32, 32), Color(255, 255, 255, 6))
        for c in self.coins:
            if not c['got']:
                c['s'].render(r.surface, self.camera)
        self.ghost.render(r.surface, self.camera)
        self.player.render(r.surface, self.camera)
        r.draw_text(Vector2(16, 12), f"Score: {self.score}", color=Color(235, 240, 250), size=22)
        r.draw_text(Vector2(W - 150, 12), f"Time: {int(self.timer)}s", color=${C(p.accentRGB)}, size=22)
        if self.over:
            r.fill_rect(Vector2(0, 0), Vector2(W, H), Color(6, 8, 14, 170))
            msg = "TIME UP — NICE LOOT!" if self.win else "CAUGHT!"
            r.draw_text(Vector2(W / 2, H / 2 - 16), msg, color=${C(p.accentRGB)} if self.win else ${C(p.enemyRGB)}, size=40)
            r.draw_text(Vector2(W / 2, H / 2 + 30), f"Score {self.score} · Space to replay", color=Color(200, 205, 220), size=18)

game = Game(title="${p.title}", size=(W, H), fps=60)
game.run(CollectScene())
`;
}

export const GAME_GENERATORS: Record<GameType, (p: GameParams) => string> = {
  snake: snakeCode,
  pong: pongCode,
  shooter: shooterCode,
  flappy: flappyCode,
  breakout: breakoutCode,
  collect: collectCode,
};

export function generateGame(type: GameType, p: GameParams): string {
  return GAME_GENERATORS[type](p);
}
