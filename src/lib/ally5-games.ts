// Ally-5 game generation kernels.
// Each generator emits a complete, runnable lapia_shim Python game —
// these templates ARE the model's training corpus (see packages/ally5-knowledge/).
"use client";

export interface GameParams {
  title: string;
  model: string; // model name shown in the generated header
  playerRGB: [number, number, number];
  enemyRGB: [number, number, number];
  accentRGB: [number, number, number];
  speed: number; // 0.8 .. 1.6
  juice: number; // 0 = nano/fast essentials · 1 = pro · 2 = max/game extra polish
  coins: number; // collectibles count where applicable
}

export type GameType =
  | "snake"
  | "pong"
  | "shooter"
  | "flappy"
  | "breakout"
  | "collect";

export const GAME_LABELS: Record<GameType, string> = {
  snake: "Snake",
  pong: "Pong",
  shooter: "Space Shooter",
  flappy: "Flappy Flier",
  breakout: "Breakout",
  collect: "Coin Collector",
};

const C = (rgb: [number, number, number]) => `Color(${rgb[0]}, ${rgb[1]}, ${rgb[2]})`;

